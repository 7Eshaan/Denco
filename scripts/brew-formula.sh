#!/bin/sh
# Writes the Homebrew formula for a Denco release to stdout (DECISIONS
# D68). The release workflow runs it after publishing a release and pushes
# the result to the tap (github.com/7Eshaan/homebrew-tap, Formula/denco.rb),
# so that
#
#   brew install 7Eshaan/tap/denco
#
# installs the release's prebuilt binary on macOS or Linux. By hand:
#
#   scripts/brew-formula.sh v0.3.2 dist/SHA256SUMS > denco.rb
#
# (DENCO_REPO_URL points elsewhere; the tests use it.)
#
# Keep this file ASCII, like install.sh.
set -eu

usage="usage: scripts/brew-formula.sh <version, e.g. v0.3.2> <SHA256SUMS file>"
[ $# -eq 2 ] || {
	echo "$usage" >&2
	exit 2
}
tag=$1
sums=$2
repo=${DENCO_REPO_URL:-https://github.com/7Eshaan/Denco}

fail() {
	echo "brew-formula: $*" >&2
	exit 1
}

case $tag in
v[0-9]*.[0-9]*.[0-9]*) ;;
*) fail "$tag isn't a version tag like v0.3.2" ;;
esac
case $tag in
*-*) fail "$tag is a pre-release; the tap only gets releases" ;;
esac
[ -r "$sums" ] || fail "can't read $sums"

# sha256 OS ARCH prints the checksum of that archive, or fails.
sha256() {
	f="denco_${tag}_$1_$2.tar.gz"
	s=$(awk -v f="$f" '$2 == f || $2 == "*" f { print $1 }' "$sums")
	case $s in
	[0-9a-f][0-9a-f][0-9a-f][0-9a-f]*) ;;
	*) fail "$f isn't listed in $sums" ;;
	esac
	[ ${#s} -eq 64 ] || fail "$f has a malformed checksum in $sums"
	echo "$s"
}

# Every checksum first, so a missing archive writes no formula at all.
darwin_arm64=$(sha256 darwin arm64)
darwin_amd64=$(sha256 darwin amd64)
linux_arm64=$(sha256 linux arm64)
linux_amd64=$(sha256 linux amd64)

url() { echo "$repo/releases/download/$tag/denco_${tag}_$1_$2.tar.gz"; }

cat <<EOF
# Generated by scripts/brew-formula.sh in $repo
# for Denco $tag. Don't edit: the next release replaces it.
class Denco < Formula
  desc "Daemon-based BitTorrent client for the command line"
  homepage "$repo"
  version "${tag#v}"
  license "MIT"

  on_macos do
    on_arm do
      url "$(url darwin arm64)"
      sha256 "$darwin_arm64"
    end
    on_intel do
      url "$(url darwin amd64)"
      sha256 "$darwin_amd64"
    end
  end

  on_linux do
    on_arm do
      url "$(url linux arm64)"
      sha256 "$linux_arm64"
    end
    on_intel do
      url "$(url linux amd64)"
      sha256 "$linux_amd64"
    end
  end

  def install
    bin.install "denco"
  end

  test do
    assert_match "denco $tag", shell_output("#{bin}/denco version")
  end
end
EOF
